"""Simulation of longitudinal covariates, the outcome, and missing-data masks."""
import numpy as np
import pandas as pd
from scipy.stats import skewnorm


# ========================================
# Time points, longitudinal data, and outcome generation
# ========================================

def generate_time_points(T):
    """Generate non-equally spaced time points."""
    time_points = []

    # First phase: daily intervals
    num_1 = int(round(0.3 * T))
    for i in range(num_1 + 1):
        time_points.append(i)

    # Second phase: weekly intervals
    interval_week = 7
    last = time_points[-1]
    for _ in range(num_1):
        last += interval_week
        time_points.append(last)

    # Third phase: monthly intervals
    interval_month = 30
    num_3 = int(round(0.4 * T))
    for _ in range(num_3):
        last += interval_month
        time_points.append(last)

    return time_points


def generate_longitudinal_data(
    T, N, M,
    rho_within=0.5,
    rho_across=0.8,
    seed=None,
    transform='lognormal',
    memory_lags=5,
    memory_tau=3.0,
):
    if seed is not None:
        np.random.seed(seed)

    # Within-time covariance across features
    base_cov = rho_within * np.ones((M, M)) + (1 - rho_within) * np.eye(M)
    L = np.linalg.cholesky(base_cov)
    data = np.zeros((T, N, M))

    # Baseline
    for i in range(N):
        data[0, i, :] = L @ np.random.randn(M)

    # Multi-lag temporal dependence
    if memory_lags < 1:
        raise ValueError("memory_lags must be >= 1")

    if memory_lags == 1:
        weights = np.array([rho_across], dtype=float)
    else:
        lags = np.arange(1, memory_lags + 1, dtype=float)
        w_raw = np.exp(-(lags - 1.0) / memory_tau)
        w_raw = w_raw / np.linalg.norm(w_raw)  # sum(w_raw^2)=1
        weights = rho_across * w_raw           # sum(weights^2)=rho_across^2

    # Recursive generation
    for t in range(1, T):
        for i in range(N):
            innovation = L @ np.random.randn(M)

            max_lag = min(memory_lags, t)
            past = np.zeros(M)
            for ell in range(1, max_lag + 1):
                past += weights[ell - 1] * data[t - ell, i, :]

            data[t, i, :] = past + np.sqrt(1 - rho_across ** 2) * innovation

    # Transformation
    if transform == 'lognormal':
        data = np.log1p(np.abs(data - np.min(data) + 1e-4))
    elif transform == 'skewnorm':
        flat_data = data.flatten()
        skewed = skewnorm.rvs(
            a=5,
            loc=np.mean(flat_data),
            scale=np.std(flat_data),
            size=flat_data.shape,
        )
        data = skewed.reshape(data.shape)

    return data


def generate_outcome_Y(
    data,
    time_points,
    f=lambda x: x,
    g=lambda t: t,
    g_scale=0,
    beta_0=2.0,
    noise_ratio=0.1,
    seed=None,
):
    """
    Generate continuous outcome Y.

    The outcome is generated by selecting 10 causal predictors from the flattened
    (time, feature) grid and adding noise.
    """
    if seed is not None:
        np.random.seed(seed)

    T, N, M = data.shape
    MT = M * T
    P = 10

    selected_indices = np.random.choice(MT, P, replace=False)
    coefs = np.random.uniform(-1, 1, size=P)

    g_term = g(time_points) * g_scale

    Y = np.zeros(N)
    for i in range(N):
        x_flat = data[:, i, :].flatten()
        x_selected = np.array([f(x_flat[j]) for j in selected_indices])
        x_term = np.dot(x_selected, coefs)
        Y[i] = beta_0 + x_term + g_term

    signal_var = np.var(Y)
    noise_var = noise_ratio / (1 - noise_ratio) * signal_var
    noise = np.random.normal(0, np.sqrt(noise_var), size=N)
    Y += noise

    return Y, selected_indices, coefs


# ========================================
# Missing mechanism helper functions
# ========================================

def sigmoid(x):
    return 1.0 / (1.0 + np.exp(-x))


def solve_alpha_for_mean_logit(
    S,
    target,
    is_missing=False,
    eligible_mask=None,
    tol=1e-4,
    max_iter=60,
):
    """
    Solve alpha numerically so that:
      - is_missing=False: mean(sigmoid(S + alpha)) is close to target
      - is_missing=True : mean(1 - sigmoid(S + alpha)) is close to target

    If eligible_mask is given, the target mean is matched only on eligible entries.
    """
    if eligible_mask is not None:
        arr = S[eligible_mask].astype(float).ravel()
    else:
        arr = S.astype(float).ravel()

    target = float(np.clip(target, 1e-4, 1 - 1e-4))

    def f(alpha):
        val = sigmoid(arr + alpha)
        if is_missing:
            val = 1.0 - val
        return val.mean() - target

    lo, hi = -20.0, 20.0
    flo, fhi = f(lo), f(hi)

    # If the root is not bracketed, use an analytic approximation.
    if flo * fhi > 0:
        m = arr.mean()
        if not is_missing:
            return np.log(target / (1 - target)) - m
        else:
            return np.log((1 - target) / target) - m

    for _ in range(max_iter):
        mid = 0.5 * (lo + hi)
        fmid = f(mid)
        if abs(fmid) < tol:
            return mid
        if flo * fmid <= 0:
            hi, fhi = mid, fmid
        else:
            lo, flo = mid, fmid

    return 0.5 * (lo + hi)


# ========================================
# Nested missing mask generation
# ========================================

def generate_nested_missing_masks(
    data,
    Y,
    mechanism='MCAR',
    missing_rates_x=(0.1, 0.2, 0.3),
    missing_rate_y=0.1,
    causal_indices=None,
    seed=None,
):
    """
    Generate nested missing masks.

    Mask definition:
      True  = observed
      False = missing

    Mechanisms:
      - MCAR:
          Each X_ijk and Y_i is missing independently.
      - MAR_causal / MAR_noncausal:
          X missingness depends on observed covariates at the (t, i) level.
          For the same (t, i), all features share the same missing indicator.
      - MNAR:
          Missingness is applied to causal covariates and depends on their own values.
    """
    if seed is not None:
        np.random.seed(seed)

    T, N, M = data.shape
    missing_rates_x = sorted(float(r) for r in missing_rates_x)
    missing_rates_x = [float(np.clip(r, 1e-3, 1 - 1e-3)) for r in missing_rates_x]
    missing_rate_y = float(np.clip(missing_rate_y, 1e-3, 1 - 1e-3))

    print(
        f"\n  [Missing generation] mechanism={mechanism}, "
        f"X rates={missing_rates_x}, Y rate={missing_rate_y}"
    )

    data_masks = {}

    # ---------- 1) MCAR ----------
    if mechanism == 'MCAR':
        U = np.random.rand(T, N, M)
        for r in missing_rates_x:
            missing = (U < r)
            mask = ~missing
            data_masks[r] = mask
            actual = 1.0 - mask.mean()
            print(f"    MCAR {r:.0%}: actual X missing = {actual:.3f}")

    # ---------- 2) MAR_causal / MAR_noncausal ----------
    elif mechanism in ['MAR_causal', 'MAR_noncausal']:
        if causal_indices is None or len(causal_indices) == 0:
            raise ValueError(f"{mechanism} needs causal_indices")

        if mechanism == 'MAR_causal':
            idx_set = list(causal_indices)
            desc = 'MAR_causal (based on causal covariates)'
        else:
            idx_set = [j for j in range(M) if j not in causal_indices]
            if len(idx_set) == 0:
                print("    Warning: no non-causal variables. Falling back to MCAR.")
                return generate_nested_missing_masks(
                    data, Y, 'MCAR', missing_rates_x,
                    missing_rate_y, None, seed
                )
            desc = 'MAR_noncausal (based on non-causal covariates)'

        print(f"    {desc}, indices = {idx_set}")

        # Score at the (t, i) level.
        # Missingness depends on covariate values, not directly on time itself.
        S2D = 0.1 * data[:, :, idx_set].sum(axis=2)  # [T, N]

        # Shared U for all features at the same (t, i).
        U2D = np.random.rand(T, N)

        probs2D = {}
        for r in missing_rates_x:
            alpha_r = solve_alpha_for_mean_logit(
                S2D,
                target=r,
                is_missing=False,
            )
            p_miss_2D = sigmoid(S2D + alpha_r)
            probs2D[r] = p_miss_2D
            print(f"    {mechanism} {r:.0%}: solved alpha = {alpha_r:.4f}")

        # Same U2D and monotone alpha values give nested missing sets.
        for r in missing_rates_x:
            p_miss_2D = probs2D[r]
            missing2D = (U2D < p_miss_2D)
            missing = np.repeat(missing2D[:, :, None], M, axis=2)
            mask = ~missing
            data_masks[r] = mask
            actual = 1.0 - mask.mean()
            print(f"    {mechanism} {r:.0%}: actual X missing = {actual:.3f}")

    # ---------- 3) MNAR ----------
    elif mechanism == 'MNAR':
        if causal_indices is None or len(causal_indices) == 0:
            print("    Warning: MNAR needs causal_indices. Falling back to MCAR.")
            return generate_nested_missing_masks(
                data, Y, 'MCAR', missing_rates_x,
                missing_rate_y, None, seed
            )

        causal_indices = list(causal_indices)
        print(f"    MNAR on causal indices: {causal_indices}")

        U = np.random.rand(T, N, M)

        S = np.zeros((T, N, M))
        eligible = np.zeros((T, N, M), dtype=bool)
        for j in causal_indices:
            S[:, :, j] = 0.2 * data[:, :, j]
            eligible[:, :, j] = True

        probs = {}
        for r in missing_rates_x:
            alpha_r = solve_alpha_for_mean_logit(
                S,
                target=r,
                is_missing=True,
                eligible_mask=eligible,
            )
            p_miss = np.zeros((T, N, M))
            p_miss[eligible] = 1.0 - sigmoid(S[eligible] + alpha_r)
            probs[r] = p_miss
            print(f"    MNAR {r:.0%}: solved alpha = {alpha_r:.4f}")

        for r in missing_rates_x:
            p_miss = probs[r]
            missing = (U < p_miss)
            mask = ~missing
            data_masks[r] = mask
            overall = 1.0 - mask.mean()
            causal_mask = mask[:, :, causal_indices]
            causal_rate = 1.0 - causal_mask.mean()
            print(
                f"    MNAR {r:.0%}: overall X missing = {overall:.3f}, "
                f"causal X missing = {causal_rate:.3f}"
            )

    else:
        raise ValueError(f"Unknown mechanism: {mechanism}")

    # ========================================
    # Generate Y missing mask
    # ========================================
    if mechanism == 'MCAR':
        Y_mask = np.random.rand(N) >= missing_rate_y

    elif mechanism in ['MAR_causal', 'MAR_noncausal']:
        if mechanism == 'MAR_causal':
            idx_set = list(causal_indices)
        else:
            idx_set = [j for j in range(M) if j not in causal_indices]

        if len(idx_set) == 0:
            print("    Warning: no available variables for Y MAR. Falling back to MCAR for Y.")
            Y_mask = np.random.rand(N) >= missing_rate_y
        else:
            features = data[:, :, idx_set]
            time_avg = features.mean(axis=0)
            feature_sum = time_avg.sum(axis=1)

            alpha_y = solve_alpha_for_mean_logit(
                feature_sum,
                target=missing_rate_y,
                is_missing=False,
            )
            p_y_miss = sigmoid(feature_sum + alpha_y)
            Y_mask = np.random.rand(N) >= p_y_miss
            print(f"    Y(MAR) solved alpha = {alpha_y:.4f}")

    elif mechanism == 'MNAR':
        alpha_y = solve_alpha_for_mean_logit(
            Y,
            target=missing_rate_y,
            is_missing=False,
        )
        p_y_miss = sigmoid(Y + alpha_y)
        Y_mask = np.random.rand(N) >= p_y_miss
        print(f"    Y(MNAR) solved alpha = {alpha_y:.4f}")

    else:
        Y_mask = np.random.rand(N) >= missing_rate_y

    actual_y = 1.0 - Y_mask.mean()
    print(f"    Y missing: actual rate = {actual_y:.3f}")

    for r, mask in data_masks.items():
        actual = 1.0 - mask.mean()
        print(f"    [Summary] {r:.0%}: actual X missing = {actual:.3f}")

    return data_masks, Y_mask


# ========================================
# Main data simulation function
# ========================================

def simulate_data(
    seed,
    T,
    N,
    M,
    noise_ratio=0.1,
    transform='lognormal',
    missing_mechanism=None,
    missing_rates_x=(0.1, 0.2, 0.3),
    missing_rate_y=0.1,
    memory_lags=5,
    memory_tau=3.0,
):
    """
    Generate complete data and optional missingness.

    Returns:
      If missing_mechanism is None:
          df_wide, df_time, Y, selected_vars, coefs
      Otherwise:
          df_wide, df_time, Y, selected_vars, coefs, data_masks, Y_mask
    """
    time_points = generate_time_points(T)
    T_actual = len(time_points)

    print(
        f"  [Data generation] seed={seed}, T_actual={T_actual}, "
        f"memory_lags={memory_lags}, memory_tau={memory_tau}"
    )

    # Complete covariates
    data = generate_longitudinal_data(
        T=T_actual,
        N=N,
        M=M,
        rho_within=0.5,
        rho_across=0.8,
        memory_lags=memory_lags,
        memory_tau=memory_tau,
        seed=seed,
        transform=transform,
    )

    # Generate Y
    f = lambda x: np.sin(np.pi * x)
    g = lambda t: np.mean(np.square(t))
    g_scale = 0

    Y, selected_vars, coefs = generate_outcome_Y(
        data=data,
        time_points=time_points,
        f=f,
        g=g,
        g_scale=g_scale,
        beta_0=2.0,
        noise_ratio=noise_ratio,
        seed=seed,
    )

    # Generate missing masks
    data_masks, Y_mask = None, None
    if missing_mechanism is not None:
        causal_indices = list(set([idx % M for idx in selected_vars]))

        data_masks, Y_mask = generate_nested_missing_masks(
            data,
            Y,
            mechanism=missing_mechanism,
            missing_rates_x=missing_rates_x,
            missing_rate_y=missing_rate_y,
            causal_indices=causal_indices,
            seed=seed,
        )

    # Generate wide-format dataframe
    wide_rows = []
    for i in range(N):
        row = [i + 1]
        for m in range(M):
            row.append(data[:, i, m].tolist())
        row.append(Y[i])
        wide_rows.append(row)

    wide_columns = ["subject"] + [f"x{j + 1}" for j in range(M)] + ["Y"]
    df_wide = pd.DataFrame(wide_rows, columns=wide_columns)

    # Time dataframe
    df_time = pd.DataFrame({
        "subject": list(range(1, N + 1)),
        "time": [time_points] * N,
    })

    if missing_mechanism is not None:
        return df_wide, df_time, Y, selected_vars, coefs, data_masks, Y_mask
    else:
        return df_wide, df_time, Y, selected_vars, coefs
